"""Markdown export of the tech pack."""


def _table(rows):
    out = []
    if rows:
        out.append("| " + " | ".join(rows[0]) + " |")
        out.append("|" + "|".join(["---"] * len(rows[0])) + "|")
        for r in rows[1:]:
            out.append("| " + " | ".join(str(x) for x in r) + " |")
    return "\n".join(out)


def generate_md(pack):
    st = pack["style"]
    s = []
    s.append(f"# Tech Pack — {st['style_name']} ({st['style_code']})")
    s.append("")
    s.append(f"**{st['brand']}** · generated {st['date']} by the Tech Pack Agent (v{st['version']})")
    s.append("")
    for n in st["notes"]:
        s.append(f"> {n}")
    s.append("")

    s.append("## 1. Style information")
    s.append(_table([
        ["Field", "Value"],
        ["Brand", st["brand"]], ["Style name", st["style_name"]],
        ["Style code", st["style_code"]], ["Season", st["season"]],
        ["Date", st["date"]], ["Version", st["version"]],
        ["Sample size", st["sample_size"]], ["Size range", st["size_range"]],
        ["Units", pack["meta"]["units"]], ["Colourway", st["colourway"]],
        ["Garment", st["garment"]],
    ]))
    s.append("")

    d = pack["drawings"]
    s.append("## 2. Technical drawings")
    s.append(f"- {d['flat_title']} (see `flat.svg`)")
    s.append("- Detail close-ups:")
    for x in d["details"]:
        s.append(f"  - {x}")
    s.append(f"- {d['photo_note']}")
    s.append("")

    s.append("## 3. Fabric specifications")
    s.append(_table([["Property", "Specification"]] + pack["fabric"]["rows"]))
    s.append("")

    s.append("## 4. Bill of materials")
    s.append(_table([["Item", "Material / specification", "Qty per piece"]] + pack["bom"]["rows"]))
    s.append("")

    m = pack["measurements"]
    s.append("## 5. Garment measurements")
    s.append(f"_{m['note']}_")
    s.append("")
    s.append(_table([["Measurement", "Where / how to measure",
                      f"Size {st['sample_size']}", "Tolerance (±)"]] + m["rows"]))
    s.append("")

    g = pack["grading"]
    s.append("## 6. Size grading")
    s.append(_table([["Measurement"] + g["sizes"] + ["Step"]] + g["rows"]))
    s.append("")
    s.append(f"_{g['rules']}_")
    s.append("")

    c = pack["construction"]
    s.append("## 7. Construction details")
    s.append(_table([["Area", "Stitch / method", "Specification"]] + c["rows"]))
    s.append("")
    s.append(_table([["Thread / machine setting", "Specification"]] + c["thread"]))
    s.append("")
    s.append(_table([["Stitch code", "Type", "SPC", "Typical use"]] + c["stitches"]))
    s.append("")

    col = pack["colours"]
    s.append("## 8. Colours and artwork")
    s.append(_table([["Role", "Colour", "Hex", "Coverage", "Suggested Pantone TCX (verify on swatch)"]]
                    + col["colorway_rows"]))
    s.append("")
    s.append(_table([["Artwork", "Size & placement (TBC)", "File spec"]] + col["artwork"]))
    s.append("")
    s.append(col["requirements"])
    s.append("")

    s.append("## 9. Labels and packaging")
    s.append(_table([["Item", "Specification", "Placement / note"]] + pack["labels_packaging"]["rows"]))
    s.append("")

    fb = pack["sample_feedback"]
    s.append("## 10. Sample feedback and revisions")
    s.append(_table([["#", "Item", "Comment", "Correction", "Date", "Status"]] + fb["rows"]))
    s.append("")
    s.append(_table([["Version", "Date", "Author", "Notes"]] + fb["revisions"]))
    s.append("")
    s.append(_table([["Role", "Name", "Date", "Signature"]] + fb["approvals"]))
    s.append("")

    if pack.get("ai") and pack["ai"].get("observations"):
        s.append("## 11. AI observations (reference only)")
        s.append(_table([["Observation", "Value"]] +
                        [[k, str(v)] for k, v in pack["ai"]["observations"].items()]))
        s.append("")

    s.append("---")
    s.append("*Generated by the Tech Pack Agent. Figures are standard production baselines — "
             "verify against the approved sample before bulk production.*")
    return "\n".join(s) + "\n"
